/**
 * Intelligent topic matcher that returns the most relevant cinema/VFX image
 */
export function getTopicImage(title: string, category: string): string {
  const t = title.toLowerCase();
  const c = category.toLowerCase();

  // 1. Specific Tool / Subject Overrides
  if (t.includes('unreal engine') || t.includes('megalights') || t.includes('lumen') || t.includes('nanite') || t.includes('epic games')) {
    return TOPIC_IMAGES.unrealEngine;
  }
  if (t.includes('davinci resolve') || t.includes('blackmagic') || t.includes('color grading') || t.includes('baselight') || t.includes('colorfront') || t.includes('aces')) {
    return TOPIC_IMAGES.davinciSuite;
  }
  if (t.includes('nuke') || t.includes('foundry') || t.includes('mari') || t.includes('compositing') || t.includes('deep comp') || t.includes('openexr')) {
    return TOPIC_IMAGES.nukeComp;
  }
  if (t.includes('arri') || t.includes('alexa') || t.includes('red v-raptor') || t.includes('venice') || t.includes('burano') || t.includes('lens') || t.includes('anamorphic') || t.includes('cooke') || t.includes('camera')) {
    return TOPIC_IMAGES.arriAlexa;
  }
  if (t.includes('sora') || t.includes('runway') || t.includes('higgsfield') || t.includes('kling') || t.includes('seedance') || t.includes('generative') || t.includes('diffusion') || t.includes('ai video')) {
    return TOPIC_IMAGES.aiVideoStudio;
  }
  if (t.includes('mocap') || t.includes('motion capture') || t.includes('vicon') || t.includes('optitrack') || t.includes('qualisys') || t.includes('shogun') || t.includes('stunt')) {
    return TOPIC_IMAGES.mocapStage;
  }
  if (t.includes('atmos') || t.includes('audio') || t.includes('pro tools') || t.includes('sound') || t.includes('foley') || t.includes('dialogue') || t.includes('mixing') || t.includes('reverb')) {
    return TOPIC_IMAGES.atmosStage;
  }
  if (t.includes('fiber') || t.includes('server') || t.includes('storage') || t.includes('nvme') || t.includes('render farm') || t.includes('datacenter') || t.includes('switch') || t.includes('pure storage') || t.includes('cisco') || t.includes('arista')) {
    return TOPIC_IMAGES.renderFarm;
  }
  if (t.includes('led volume') || t.includes('stagecraft') || t.includes('roe visual') || t.includes('brompton') || t.includes('megapixel') || t.includes('helios') || t.includes('icvfx') || t.includes('in-camera vfx')) {
    return TOPIC_IMAGES.ledVolume;
  }
  if (t.includes('creature') || t.includes('dune') || t.includes('houdini') || t.includes('fluid') || t.includes('pyro') || t.includes('sand') || t.includes('explosion') || t.includes('simulation') || t.includes('embergen')) {
    return TOPIC_IMAGES.creatureVfx;
  }
  if (t.includes('blender') || t.includes('maya') || t.includes('zbrush') || t.includes('substance') || t.includes('geometry nodes') || t.includes('3d')) {
    return TOPIC_IMAGES.blender3d;
  }
  if (t.includes('netflix') || t.includes('affleck') || t.includes('interpositive') || t.includes('deal') || t.includes('acquisition') || t.includes('paramount') || t.includes('universal') || t.includes('disney') || t.includes('warner')) {
    return TOPIC_IMAGES.hollywoodBacklot;
  }
  if (t.includes('adobe') || t.includes('topaz') || t.includes('premiere') || t.includes('after effects') || t.includes('frame.io')) {
    return TOPIC_IMAGES.adobeStudio;
  }

  // 2. Category Fallbacks
  switch (c) {
    case 'tools':
      return TOPIC_IMAGES.davinciReview;
    case 'virtualproduction':
    case 'virtual-production':
      return TOPIC_IMAGES.virtualStage;
    case 'vfx':
      return TOPIC_IMAGES.vfxBreakdown;
    case 'ai':
      return TOPIC_IMAGES.heroAiFilm;
    case 'tech':
      return TOPIC_IMAGES.cinemaRig;
    case 'hollywood':
    default:
      return TOPIC_IMAGES.directorChair;
  }
}
